def test_orders_does_not_declare_the_circular_foreign_key() -> None:
    targets = {foreign_key.target_fullname for foreign_key in orders_tables.orders.foreign_keys}

    assert targets == {"customers.id"}


def test_the_invoice_indexes_are_named() -> None:
    assert (
        _index_ddl("invoices", "invoices_number_key")
        == "CREATE UNIQUE INDEX invoices_number_key ON invoices (number)"
    )
    assert (
        _index_ddl("invoices", "invoices_order_key")
        == "CREATE UNIQUE INDEX invoices_order_key ON invoices (order_id)"
    )
    assert (
        _index_ddl("invoices", "invoices_created_at_id_idx")
        == "CREATE INDEX invoices_created_at_id_idx ON invoices (created_at DESC, id DESC)"
    )
    assert (
        _index_ddl("invoice_lines", "ix_invoice_lines_invoice_id")
        == "CREATE INDEX ix_invoice_lines_invoice_id ON invoice_lines (invoice_id)"
    )
    assert (
        _index_ddl("payments", "ix_payments_invoice_id")
        == "CREATE INDEX ix_payments_invoice_id ON payments (invoice_id)"
    )


def test_invoice_number_sequence_starts_at_one() -> None:
    assert invoices_tables.invoice_number_seq.name == "invoice_number_seq"
    assert invoices_tables.invoice_number_seq.start == 1
