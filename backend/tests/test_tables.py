def _table_ddl(name: str) -> str:
    return " ".join(str(CreateTable(metadata.tables[name]).compile(dialect=DIALECT)).split())


def _index_ddl(table: str, name: str) -> str:
    index = next(index for index in metadata.tables[table].indexes if index.name == name)
    return " ".join(str(CreateIndex(index).compile(dialect=DIALECT)).split())


def test_metadata_holds_every_table() -> None:
    assert set(metadata.tables) == TABLES

    indexes = {index.name for name in TABLES for index in metadata.tables[name].indexes}
    assert indexes == INDEXES


