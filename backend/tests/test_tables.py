from __future__ import annotations

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.infra.db import metadata
from app.modules.auth import tables as auth_tables  # noqa: F401
from app.modules.customers import tables as customers_tables  # noqa: F401

DIALECT = postgresql.dialect()
TABLES = {"users", "sessions", "customers"}
INDEXES = {
    "users_email_lower_key",
    "sessions_last_seen_at_idx",
    "customers_email_lower_key",
    "customers_created_at_id_idx",
}


def _table_ddl(name: str) -> str:
    return " ".join(str(CreateTable(metadata.tables[name]).compile(dialect=DIALECT)).split())


def _index_ddl(table: str, name: str) -> str:
    index = next(index for index in metadata.tables[table].indexes if index.name == name)
    return " ".join(str(CreateIndex(index).compile(dialect=DIALECT)).split())


def test_metadata_holds_the_three_tables() -> None:
    assert set(metadata.tables) == TABLES

    indexes = {index.name for name in TABLES for index in metadata.tables[name].indexes}
    assert indexes == INDEXES


def test_users_table_ddl() -> None:
    ddl = _table_ddl("users")

    assert "CREATE TABLE users" in ddl
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "name TEXT NOT NULL" in ddl
    assert "email TEXT NOT NULL" in ddl
    assert "role TEXT NOT NULL" in ddl
    assert "password_hash TEXT NOT NULL" in ddl
    assert "created_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
    assert "version INTEGER DEFAULT 1 NOT NULL" in ddl
    assert "CONSTRAINT pk_users PRIMARY KEY (id)" in ddl
    assert (
        "CONSTRAINT ck_users_role CHECK (role IN ('admin', 'sales', 'finance', 'readonly'))" in ddl
    )


def test_sessions_table_ddl() -> None:
    ddl = _table_ddl("sessions")

    assert "CREATE TABLE sessions" in ddl
    assert "token_hash TEXT NOT NULL" in ddl
    assert "user_id INTEGER NOT NULL" in ddl
    assert "created_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
    assert "last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
    assert "CONSTRAINT pk_sessions PRIMARY KEY (token_hash)" in ddl
    assert (
        "CONSTRAINT fk_sessions_user_id_users FOREIGN KEY(user_id) "
        "REFERENCES users (id) ON DELETE CASCADE" in ddl
    )


def test_customers_table_ddl() -> None:
    ddl = _table_ddl("customers")

    assert "CREATE TABLE customers" in ddl
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "name TEXT NOT NULL" in ddl
    assert "email TEXT NOT NULL" in ddl
    assert "phone TEXT," in ddl
    assert "tax_id TEXT," in ddl
    assert "address TEXT," in ddl
    assert "status TEXT NOT NULL" in ddl
    assert "version INTEGER NOT NULL" in ddl
    assert "created_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
    assert "updated_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl
    assert "name_search TEXT NOT NULL" in ddl
    assert "email_search TEXT NOT NULL" in ddl
    assert "CONSTRAINT pk_customers PRIMARY KEY (id)" in ddl
    assert "CONSTRAINT ck_customers_status CHECK (status IN ('active', 'inactive'))" in ddl


def test_index_ddl() -> None:
    assert (
        _index_ddl("users", "users_email_lower_key")
        == "CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email))"
    )
    assert (
        _index_ddl("sessions", "sessions_last_seen_at_idx")
        == "CREATE INDEX sessions_last_seen_at_idx ON sessions (last_seen_at)"
    )
    assert (
        _index_ddl("customers", "customers_email_lower_key")
        == "CREATE UNIQUE INDEX customers_email_lower_key ON customers (lower(email))"
    )
    assert (
        _index_ddl("customers", "customers_created_at_id_idx")
        == "CREATE INDEX customers_created_at_id_idx ON customers "
        "(created_at DESC, id DESC)"
    )


def test_datetime_columns_store_timezones() -> None:
    for name in TABLES:
        for column in metadata.tables[name].columns:
            if column.name in {"created_at", "updated_at", "last_seen_at"}:
                assert column.type.timezone is True
