def test_qualified_sequence_name_with_a_schema() -> None:
    engine = create_db_engine(Settings(database_url=DATABASE_URL, database_schema=SCHEMA))

    assert (
        qualified_sequence_name(engine, orders_tables.order_number_seq)
        == f"{SCHEMA}.order_number_seq"
    )


def test_index_ddl() -> None:
    assert (
        _index_ddl("users", "users_email_lower_key")
        == "CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email))"
    )
    assert (
        _index_ddl("sessions", "sessions_last_seen_at_idx")
        == "CREATE INDEX sessions_last_seen_at_idx ON sessions (last_seen_at)"
    )
    assert (
        _index_ddl("customers", "customers_email_lower_key")
        == "CREATE UNIQUE INDEX customers_email_lower_key ON customers (lower(email))"
    )
    assert (
        _index_ddl("customers", "customers_created_at_id_idx")
        == "CREATE INDEX customers_created_at_id_idx ON customers "
        "(created_at DESC, id DESC)"
    )
    assert (
        _index_ddl("products", "products_sku_key")
        == "CREATE UNIQUE INDEX products_sku_key ON products (sku)"
    )
    assert (
        _index_ddl("orders", "orders_number_key")
        == "CREATE UNIQUE INDEX orders_number_key ON orders (number)"
    )
    assert (
        _index_ddl("orders", "orders_created_at_id_idx")
        == "CREATE INDEX orders_created_at_id_idx ON orders (created_at DESC, id DESC)"
    )
    assert (
        _index_ddl("orders", "ix_orders_customer_id")
        == "CREATE INDEX ix_orders_customer_id ON orders (customer_id)"
    )
    assert (
        _index_ddl("order_lines", "order_lines_order_product_key")
        == "CREATE UNIQUE INDEX order_lines_order_product_key ON order_lines "
        "(order_id, product_id)"
    )
    assert (
        _index_ddl("order_lines", "ix_order_lines_order_id")
        == "CREATE INDEX ix_order_lines_order_id ON order_lines (order_id)"
    )


def test_datetime_columns_store_timezones() -> None:
    for name in TABLES:
        for column in metadata.tables[name].columns:
            if column.name in {"created_at", "updated_at", "last_seen_at"}:
                assert column.type.timezone is True
