"""The fault rules table and its named constraints and defaults."""

from __future__ import annotations

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from app.infra.db import metadata
from app.modules.testcontrols import tables as testcontrols_tables

DIALECT = postgresql.dialect()


def _table_ddl(name: str) -> str:
    return " ".join(str(CreateTable(metadata.tables[name]).compile(dialect=DIALECT)).split())


def test_fault_rules_table_ddl() -> None:
    ddl = _table_ddl("fault_rules")

    assert "CREATE TABLE fault_rules" in ddl
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "target TEXT NOT NULL" in ddl
    assert "method TEXT," in ddl
    assert "path TEXT," in ddl
    assert "latency_ms INTEGER DEFAULT 0 NOT NULL" in ddl
    assert "status INTEGER," in ddl
    assert "remaining INTEGER," in ddl
    assert "created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL" in ddl
    assert "CONSTRAINT pk_fault_rules PRIMARY KEY (id)" in ddl
    assert "CONSTRAINT ck_fault_rules_target CHECK (target IN ('route', 'gateway'))" in ddl
    assert (
        "CONSTRAINT ck_fault_rules_method CHECK "
        "(method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE'))" in ddl
    )
    assert (
        "CONSTRAINT ck_fault_rules_latency_ms CHECK "
        "(latency_ms >= 0 AND latency_ms <= 10000)" in ddl
    )
    assert "CONSTRAINT ck_fault_rules_status CHECK (status >= 400 AND status <= 599)" in ddl
    assert "CONSTRAINT ck_fault_rules_remaining CHECK (remaining >= 0)" in ddl


def test_fault_rules_has_no_named_indexes() -> None:
    assert testcontrols_tables.fault_rules.indexes == set()
